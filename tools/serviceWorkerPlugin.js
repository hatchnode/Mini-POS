/**
 * Vite plugin: after a production build, write `sw.js` next to index.html. The service worker
 * keeps a copy of every built file on the device, so the app opens with no internet at all
 * (orders were already stored locally; this covers loading the app itself).
 *
 * The cache name is a hash of the built files, so each new build replaces the old copy the next
 * time the app is opened online.
 */
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

const SW_FILE = 'sw.js';

function listFiles(dir, root = dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name);
    return entry.isDirectory() ? listFiles(path, root) : [relative(root, path).split(sep).join('/')];
  });
}

const serviceWorkerSource = (cacheName, files) => `// Generated by tools/serviceWorkerPlugin.js. Do not edit.
const CACHE = ${JSON.stringify(cacheName)};
const FILES = ${JSON.stringify(files)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      .then((cache) => cache.addAll(FILES))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((names) =>
        Promise.all(names.filter((n) => n.startsWith('mini-pos-') && n !== CACHE).map((n) => caches.delete(n))),
      )
      .then(() => self.clients.claim()),
  );
});

// Serve the saved copy first; fall back to the network, and to the app page when offline.
self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET' || new URL(request.url).origin !== self.location.origin) return;
  event.respondWith(
    caches.open(CACHE).then(async (cache) => {
      const saved = await cache.match(request, { ignoreSearch: true });
      if (saved) return saved;
      try {
        return await fetch(request);
      } catch (error) {
        if (request.mode === 'navigate') return cache.match('./');
        throw error;
      }
    }),
  );
});
`;

export function serviceWorkerPlugin() {
  let outDir = 'dist';
  return {
    name: 'mini-pos-service-worker',
    apply: 'build',
    configResolved(config) {
      outDir = join(config.root, config.build.outDir);
    },
    closeBundle() {
      const files = listFiles(outDir)
        .filter((f) => f !== SW_FILE)
        .sort();
      const hash = createHash('sha256');
      for (const f of files) hash.update(f).update(readFileSync(join(outDir, f)));
      const cacheName = `mini-pos-${hash.digest('hex').slice(0, 12)}`;
      // './' is the app page itself, however the server names it.
      writeFileSync(join(outDir, SW_FILE), serviceWorkerSource(cacheName, ['./', ...files]));
    },
  };
}
